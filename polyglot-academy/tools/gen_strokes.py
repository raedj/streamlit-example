#!/usr/bin/env python3
"""Generates Kotlin stroke data from content/hanzi/strokes.tsv.

Run from the project root:  python3 tools/gen_strokes.py
Output: core/src/commonMain/kotlin/com/polyglot/academy/core/mandarin/generated/
  StrokeData<NN>.kt   chunks of rows ("<char>\\t<strokes>", same format as the TSV), loaded lazily
  GeneratedStrokes.kt index of the chunks

The data is a modified version of Make Me a Hanzi's graphics.txt and stays under the Arphic Public
License (content/hanzi/ARPHICPL.TXT); every generated file says so in its header. It is a separate
work aggregated with the app, not part of the app's own code.
"""
import os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'content', 'hanzi', 'strokes.tsv')
out = os.path.join(root, 'core', 'src', 'commonMain', 'kotlin', 'com', 'polyglot', 'academy', 'core', 'mandarin', 'generated')
CHUNK = 250

rows = []
for n, line in enumerate(open(src, encoding='utf-8'), 1):
    line = line.rstrip('\n')
    if not line or line.startswith('#'):
        continue
    parts = line.split('\t')
    if len(parts) != 2 or len(parts[0]) != 1 or not parts[1]:
        sys.exit(f'{src}:{n}: expected "<character>\\t<strokes>"')
    for stroke in parts[1].split(';'):
        for pt in stroke.split(' '):
            xy = pt.split(',')
            if len(xy) != 2 or not all(v.lstrip('-').isdigit() for v in xy):
                sys.exit(f'{src}:{n}: bad point {pt!r}')
    rows.append(line)

header = ('// GENERATED by tools/gen_strokes.py from content/hanzi/strokes.tsv — do not edit by hand.\n'
          '// Stroke data: modified from Make Me a Hanzi (graphics.txt, derived from Arphic PL KaitiM GB and\n'
          '// Arphic PL UKai), licensed under the Arphic Public License — see content/hanzi/ARPHICPL.TXT.\n'
          'package com.polyglot.academy.core.mandarin.generated\n\n')

os.makedirs(out, exist_ok=True)
for old in os.listdir(out):
    if old.startswith('StrokeData') and old.endswith('.kt'):
        os.remove(os.path.join(out, old))
chunks = [rows[i:i + CHUNK] for i in range(0, len(rows), CHUNK)]
names = []
for i, chunk in enumerate(chunks, 1):
    name = f'StrokeData{i:02d}'
    names.append(name)
    with open(os.path.join(out, name + '.kt'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(header + f'internal object {name} {{\n    val rows: List<String> = listOf(\n')
        for r in chunk:
            f.write('        "' + r.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t').replace('$', '\\$') + '",\n')
        f.write('    )\n}\n')
with open(os.path.join(out, 'GeneratedStrokes.kt'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(header + '/** All generated stroke rows ("<char>\\t<strokes>"). */\ninternal object GeneratedStrokes {\n'
            '    fun rows(): List<String> = ' + ' + '.join(f'{n}.rows' for n in names) + '\n}\n')
print(f'generated {len(rows)} characters in {len(chunks)} chunks')
