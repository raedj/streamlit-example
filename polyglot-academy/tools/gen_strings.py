#!/usr/bin/env python3
"""Generates ui/src/commonMain/.../i18n/{Keys,EnglishStrings,ArabicStrings}.kt from ui/strings/*.strings.

Each line: KEY ¦ English ¦ Arabic  (the broken-bar character separates columns). Lines starting with '#' are comments.
Plural entries separate CLDR forms with '|': English one|other, Arabic zero|one|two|few|many|other.
Run from the repository root of the Android project:  python3 tools/gen_strings.py
"""
import glob, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows, seen = [], set()
for path in sorted(glob.glob(os.path.join(root, 'ui', 'strings', '*.strings'))):
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'):
            continue
        parts = [p.strip() for p in line.split('¦')]
        if len(parts) != 3:
            sys.exit(f"{path}:{n}: expected 3 '¦'-separated columns, got {len(parts)}: {line!r}")
        key, en, ar = parts
        if key in seen:
            sys.exit(f"{path}:{n}: duplicate key {key}")
        seen.add(key)
        rows.append((key, en, ar))

def lit(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'

out = os.path.join(root, 'uicore', 'src', 'commonMain', 'kotlin', 'com', 'polyglot', 'academy', 'ui', 'i18n')
hdr = "// GENERATED by tools/gen_strings.py from ui/strings/*.strings — do not edit by hand.\npackage com.polyglot.academy.ui.i18n\n\n"
with open(os.path.join(out, 'Keys.kt'), 'w', encoding='utf-8') as f:
    f.write(hdr + "@Suppress(\"EnumEntryName\")\nenum class K {\n")
    for key, _, _ in rows:
        f.write(f"    {key},\n")
    f.write("}\n")
for name, idx in (('EnglishStrings', 1), ('ArabicStrings', 2)):
    with open(os.path.join(out, name + '.kt'), 'w', encoding='utf-8') as f:
        f.write(hdr + f"internal object {name} {{\n    val table: Map<K, String> by lazy {{ mapOf(\n")
        for r in rows:
            f.write(f"        K.{r[0]} to {lit(r[idx])},\n")
        f.write("    ) }\n}\n")
print(f"generated {len(rows)} keys")
